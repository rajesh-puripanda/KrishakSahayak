/**
 * Calculates comprehensive expenditure and assesses whether renting the selected
 * fleet of machines is Suggestable / Cost-Effective or a Potential Loss for the farmer.
 *
 * @param {Array} selectedMachines - Array of { machine, durationDays }
 * @param {number} acres - Farmer's cultivable acreage
 * @param {string} crop - Farmer's current crop
 * @returns {Object} Feasibility and expenditure analysis
 */
export function calculateMachineryExpenditureAndROI(selectedMachines, acres = 2.0, crop = "Tomato") {
 if (!selectedMachines || selectedMachines.length === 0) {
 return {
 totalExpenditure: 0,
 manualLaborCostEst: 0,
 netBenefit: 0,
 feasibilityStatus: "NO_SELECTION",
 badgeColor: "#8A7B68",
 headline: "Select machinery to analyze cost feasibility",
 detailedAdvice: "Select one or more machines to calculate rental expenditure and evaluate whether it will save you money or create a financial loss."
 };
 }

 let totalExpenditure = 0;
 let estimatedManualLaborCost = 0;
 let hasOvercapacityRisk = false;
 let hasSmallPlotLossWarning = false;
 const machineBreakdown = [];

 const manualDailyWage = 400; // Standard agricultural daily labor wage in INR

 selectedMachines.forEach(({ machine, durationDays = 1 }) => {
 const cost = machine.pricePerDay * durationDays;
 totalExpenditure += cost;

 // Estimate manual labor cost that would otherwise be required for this task
 let laborReplacedPerDay = 6;
 if (machine.category === "Harvest") laborReplacedPerDay = 18;
 else if (machine.category === "Tractor") laborReplacedPerDay = 10;
 else if (machine.category === "Tillage") laborReplacedPerDay = 8;
 else if (machine.category === "Sowing") laborReplacedPerDay = 7;
 else if (machine.category === "Spraying") laborReplacedPerDay = 4;

 const manualCostForTask = Math.round(laborReplacedPerDay * manualDailyWage * Math.min(durationDays, Math.ceil(acres)));
 estimatedManualLaborCost += manualCostForTask;

 // Check plot size vs machine economics
 const isBelowMin = acres < (machine.optimalAcresMin || 1.0);
 const isAboveMax = acres > (machine.optimalAcresMax || 10.0);

 if (isBelowMin && machine.pricePerDay >= 1500) {
 hasSmallPlotLossWarning = true;
 }
 if (isBelowMin && durationDays > 2) {
 hasOvercapacityRisk = true;
 }

 machineBreakdown.push({
 id: machine.id,
 name: machine.name,
 days: durationDays,
 cost,
 manualAlternative: manualCostForTask,
 savings: manualCostForTask - cost,
 isBelowMin
 });
 });

 const netSavings = estimatedManualLaborCost - totalExpenditure;
 const costRatio = estimatedManualLaborCost > 0 ? totalExpenditure / estimatedManualLaborCost : 1;

 let feasibilityStatus = "SUGGESTABLE";
 let badgeColor = "#6B8F5C";
 let badgeText = "Highly Suggestable (Cost Saver)";
 let headline = "";
 let detailedAdvice = "";

 if (hasSmallPlotLossWarning && acres <= 1.2) {
 feasibilityStatus = "HIGH_LOSS_RISK";
 badgeColor = "#B8492E";
 badgeText = "Loss Risk for Small Plot (< 1.5 Acres)";
 headline = "Renting heavy machinery on a small landholding will increase your debt burden.";
 detailedAdvice = `Your farm size is ${acres} acres. Renting heavy equipment like the Combine Harvester at ₹${totalExpenditure.toLocaleString('en-IN')} is too costly for this acreage and will likely lead to an unnecessary financial loss. We strongly suggest pooling with neighboring farmers in ${crop} clusters or choosing lighter equipment (e.g. Power Tiller / Multi-Crop Thresher) to protect your margins.`;
 } else if (netSavings < 0 || costRatio > 1.2) {
 feasibilityStatus = "HIGH_EXPENSE_WARNING";
 badgeColor = "#C97D34";
 badgeText = "High Expenditure (Marginal Benefit)";
 headline = `Total rental cost (₹${totalExpenditure.toLocaleString('en-IN')}) exceeds estimated manual labor costs (₹${estimatedManualLaborCost.toLocaleString('en-IN')}).`;
 detailedAdvice = `For your ${acres}-acre plot, the multi-machine rental will cost ₹${Math.abs(netSavings).toLocaleString('en-IN')} more than hiring local laborers. Consider reducing rental days or sharing the tractor with nearby farms in your village.`;
 } else if (netSavings >= 1000) {
 feasibilityStatus = "HIGHLY_SUGGESTABLE";
 badgeColor = "#6B8F5C";
 badgeText = "Highly Suggestable (High ROI)";
 headline = `Saves approx. ₹${netSavings.toLocaleString('en-IN')} compared to manual labor!`;
 detailedAdvice = `Renting these ${selectedMachines.length} machine(s) for ${acres} acres will speed up field operations before monsoon fluctuations and save ₹${netSavings.toLocaleString('en-IN')} compared to hiring ${Math.round(estimatedManualLaborCost / manualDailyWage)} manual day-laborers. This prevents crop loss and ensures optimal soil pulverization.`;
 } else {
 feasibilityStatus = "SUGGESTABLE";
 badgeColor = "#6B8F5C";
 badgeText = "Suggestable (Cost Effective)";
 headline = `Saves approx. ₹${Math.max(200, netSavings).toLocaleString('en-IN')} in operational time & expenses.`;
 detailedAdvice = `The rental expenditure of ₹${totalExpenditure.toLocaleString('en-IN')} is well balanced for ${acres} acres of ${crop}. It replaces tedious manual work and finishes before crucial weather windows.`;
 }

 return {
 totalExpenditure,
 estimatedManualLaborCost,
 netSavings,
 feasibilityStatus,
 badgeColor,
 badgeText,
 headline,
 detailedAdvice,
 machineBreakdown
 };
}

